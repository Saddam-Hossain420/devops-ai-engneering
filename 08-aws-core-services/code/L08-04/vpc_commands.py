#!/usr/bin/env python3
"""vpc_commands.py — L07-04-এর subnet plan (`subnet_plan.py --json`) থেকে VPC তৈরির AWS CLI script **ছাপে**; কিছু চালায় না।

  python3 ../../../07-cloud-fundamentals/code/L07-04/subnet_plan.py plan.json --json > subnets-plan.json
  python3 vpc_commands.py subnets-plan.json --vpc-cidr 10.20.0.0/16 --region ap-south-1 --name lab08 > create-vpc.sh
  less create-vpc.sh        # পড়ুন, তারপর: bash create-vpc.sh

প্রতিটি resource-এ Name ও Project tag (L08-12-এর cleanup এই tag দিয়ে খোঁজে)। Public subnet → IGW route; private →
NAT (--nat per-az | single) বা কিছু নয় (--nat none, default — NAT ঘণ্টা ও GB অনুযায়ী চার্জযোগ্য); isolated → শুধু local।
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import re
import sys
from pathlib import Path

SAFE = re.compile(r"^[A-Za-z0-9-]{1,40}$")


def tags(resource_type: str, name: str, project: str) -> str:
    return (f"--tag-specifications 'ResourceType={resource_type},"
            f"Tags=[{{Key=Name,Value={name}}},{{Key=Project,Value={project}}}]'")


def var(tier: str, az: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", f"{tier}_{az}".upper())


def script(subnets: list[dict], vpc_cidr: str, region: str, name: str, nat: str) -> str:
    vpc_net = ipaddress.ip_network(vpc_cidr)
    for s in subnets:
        if not ipaddress.ip_network(s["cidr"]).subnet_of(vpc_net):
            raise ValueError(f"{s['cidr']} is outside {vpc_cidr}")
    types = {s["type"] for s in subnets}
    if nat != "none" and "public" not in types:
        raise ValueError("a NAT gateway needs a public subnet")
    q = "--output text --query"
    lines = ["#!/usr/bin/env bash", f"# generated by vpc_commands.py — VPC {name} ({vpc_cidr}) in {region}",
             "# review before running; every resource is tagged Project=" + name, "set -euo pipefail",
             f"export AWS_REGION={region}", "",
             f"VPC=$(aws ec2 create-vpc --cidr-block {vpc_cidr} {tags('vpc', name, name)} {q} Vpc.VpcId)",
             "aws ec2 modify-vpc-attribute --vpc-id \"$VPC\" --enable-dns-hostnames '{\"Value\":true}'",
             'echo "vpc $VPC"', ""]
    if "public" in types:
        lines += [f"IGW=$(aws ec2 create-internet-gateway {tags('internet-gateway', name + '-igw', name)} "
                  f"{q} InternetGateway.InternetGatewayId)",
                  'aws ec2 attach-internet-gateway --internet-gateway-id "$IGW" --vpc-id "$VPC"',
                  f"RT_PUBLIC=$(aws ec2 create-route-table --vpc-id \"$VPC\" {tags('route-table', name + '-public', name)} "
                  f"{q} RouteTable.RouteTableId)",
                  'aws ec2 create-route --route-table-id "$RT_PUBLIC" --destination-cidr-block 0.0.0.0/0 '
                  '--gateway-id "$IGW" >/dev/null', ""]
    for s in subnets:
        v, label = var(s["tier"], s["az"]), f"{name}-{s['tier']}-{s['az']}"
        lines.append(f"{v}=$(aws ec2 create-subnet --vpc-id \"$VPC\" --cidr-block {s['cidr']} "
                     f"--availability-zone {region}{s['az']} {tags('subnet', label, name)} "
                     f"{q} Subnet.SubnetId)")
        if s["type"] == "public":
            lines.append(f'aws ec2 associate-route-table --route-table-id "$RT_PUBLIC" --subnet-id "${v}" >/dev/null')
    lines.append("")

    azs = sorted({s["az"] for s in subnets})
    public_by_az = {s["az"]: var(s["tier"], s["az"]) for s in subnets if s["type"] == "public"}
    nat_azs = azs if nat == "per-az" else [min(public_by_az)] if nat == "single" else []
    for az in nat_azs:
        if az not in public_by_az:
            raise ValueError(f"--nat per-az needs a public subnet in AZ {az}")
        lines += [f"EIP_{az.upper()}=$(aws ec2 allocate-address --domain vpc {tags('elastic-ip', f'{name}-nat-{az}', name)} "
                  f"{q} AllocationId)",
                  f"NAT_{az.upper()}=$(aws ec2 create-nat-gateway --subnet-id \"${public_by_az[az]}\" "
                  f"--allocation-id \"$EIP_{az.upper()}\" {tags('natgateway', f'{name}-nat-{az}', name)} "
                  f"{q} NatGateway.NatGatewayId)"]
    if nat_azs:
        lines += ["aws ec2 wait nat-gateway-available --nat-gateway-ids "
                  + " ".join(f'"$NAT_{az.upper()}"' for az in nat_azs), ""]
    for s in subnets:
        if s["type"] == "public":
            continue
        v, label = var(s["tier"], s["az"]), f"{name}-{s['tier']}-{s['az']}"
        rt = f"RT_{v}"
        lines += [f"{rt}=$(aws ec2 create-route-table --vpc-id \"$VPC\" "
                  f"{tags('route-table', label, name)} {q} RouteTable.RouteTableId)",
                  f'aws ec2 associate-route-table --route-table-id "${rt}" --subnet-id "${v}" >/dev/null']
        if s["type"] == "private" and nat_azs:
            target = s["az"] if nat == "per-az" else nat_azs[0]
            lines.append(f'aws ec2 create-route --route-table-id "${rt}" --destination-cidr-block 0.0.0.0/0 '
                         f'--nat-gateway-id "$NAT_{target.upper()}" >/dev/null')
    lines += ["", 'echo "done — check: python3 vpc_audit.py (see L08-04 Section 9)"']
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description="Print an AWS CLI script that creates a VPC from a subnet plan.")
    ap.add_argument("plan", type=Path, help="output of subnet_plan.py --json")
    ap.add_argument("--vpc-cidr", required=True)
    ap.add_argument("--region", required=True)
    ap.add_argument("--name", required=True, help="Name prefix and Project tag")
    ap.add_argument("--nat", choices=("none", "single", "per-az"), default="none")
    a = ap.parse_args(argv)
    try:
        if not SAFE.match(a.name) or not re.match(r"^[a-z]{2}(-[a-z]+)+-\d$", a.region):
            raise ValueError("name: letters/digits/-; region like ap-south-1")
        plan = json.loads(a.plan.read_text(encoding="utf-8"))
        text = script(plan["subnets"], a.vpc_cidr, a.region, a.name, a.nat)
    except (OSError, KeyError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    sys.stdout.write(text)
    if a.nat != "none":
        print(f"note: --nat {a.nat} creates NAT gateway(s) + Elastic IP(s) — billed per hour and per GB from creation "
              "until deleted; see the VPC pricing page", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
