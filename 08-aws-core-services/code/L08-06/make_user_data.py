#!/usr/bin/env python3
"""make_user_data.py — TaskFlow API (L05-13) একটি EC2 user-data script-এ ভরে দেয়: app gzip+base64-এ embed, sha256 যাচাই,
আলাদা system user, hardened systemd unit। Internet বা NAT লাগে না — Ubuntu AMI-র python3-ই যথেষ্ট (app শুধু stdlib)।

  python3 make_user_data.py --out user-data.sh
  python3 userdata_lint.py user-data.sh
  aws ec2 run-instances … --user-data file://user-data.sh

সীমা: EC2 user data সর্বোচ্চ 16 KB (base64-এর আগে) — বেশি হলে error। প্রতিটি instance-এর নিজস্ব SQLite file (lab-এর জন্য;
একাধিক instance-এ data ভাগ হয় না — managed database পরে)।
"""
from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP = HERE.parents[2] / "05-python-for-infrastructure" / "code" / "L05-13" / "taskflow_api.py"
USER_DATA_LIMIT = 16 * 1024

UNIT = """\
[Unit]
Description=TaskFlow API
After=network-online.target
Wants=network-online.target

[Service]
User=taskflow
Group=taskflow
Environment=TASKFLOW_HOST=0.0.0.0
Environment=TASKFLOW_PORT={port}
Environment=TASKFLOW_DB=/var/lib/taskflow/taskflow.db
ExecStart=/usr/bin/python3 /opt/taskflow/taskflow_api.py
Restart=on-failure
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
ReadWritePaths=/var/lib/taskflow

[Install]
WantedBy=multi-user.target
"""


def build(app: bytes, port: int) -> str:
    digest = hashlib.sha256(app).hexdigest()
    payload = "\n".join(textwrap.wrap(base64.b64encode(gzip.compress(app, 9, mtime=0)).decode(), 76))
    return f"""#!/bin/bash
# generated by make_user_data.py — TaskFlow API, sha256 {digest}
# runs once as root on first boot (cloud-init); log: /var/log/cloud-init-output.log
set -euo pipefail

id taskflow >/dev/null 2>&1 || useradd --system --home-dir /opt/taskflow --shell /usr/sbin/nologin taskflow
install -d -o root -g root -m 0755 /opt/taskflow
install -d -o taskflow -g taskflow -m 0750 /var/lib/taskflow

base64 -d <<'B64' | gunzip > /opt/taskflow/taskflow_api.py
{payload}
B64
echo "{digest}  /opt/taskflow/taskflow_api.py" | sha256sum -c -
chmod 0644 /opt/taskflow/taskflow_api.py

cat > /etc/systemd/system/taskflow.service <<'UNIT'
{UNIT.format(port=port)}UNIT
systemctl daemon-reload
systemctl enable --now taskflow.service

for i in $(seq 1 20); do
  if python3 -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:{port}/health', timeout=2)"; then
    echo "taskflow healthy"; exit 0
  fi
  sleep 1
done
echo "taskflow did not become healthy — journalctl -u taskflow" >&2
exit 1
"""


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description="Build EC2 user data that installs the TaskFlow API.")
    ap.add_argument("--app", type=Path, default=APP)
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    try:
        text = build(a.app.read_bytes(), a.port)
    except OSError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    size = len(text.encode())
    if size > USER_DATA_LIMIT:
        print(f"error: user data is {size} bytes, limit {USER_DATA_LIMIT}", file=sys.stderr)
        return 1
    a.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {a.out} ({size} bytes of {USER_DATA_LIMIT}); app sha256 {hashlib.sha256(a.app.read_bytes()).hexdigest()[:16]}…")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
